import { test, expect } from "@playwright/test";

test("income/expense entry, saved rules, bulk category editing, deletion and persistent recovery", async ({ page, request }, testInfo) => {
  const credentials = { username: "tools-" + Date.now(), passwordHash: "Test-Rands-2026!" };
  expect((await request.post("/api/auth/register", { data: credentials })).ok()).toBeTruthy();
  await page.goto("/login");
  await page.getByLabel("Username", { exact: true }).fill(credentials.username);
  await page.getByLabel("Password", { exact: true }).fill(credentials.passwordHash);
  await page.getByRole("button", { name: "Login", exact: true }).click();
  await page.getByLabel("Month", { exact: true }).fill("2026-09");
  await page.getByRole("link", { name: "Category rules", exact: true }).click();
  await page.getByLabel("Description contains", { exact: true }).fill("Checkers");
  await page.getByLabel("Category", { exact: true }).selectOption("Groceries");
  await page.getByRole("button", { name: "Save category rule", exact: true }).click();
  await expect(page.getByText("Category rule saved.", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("category-rules.png"), fullPage: true });
  await page.getByRole("link", { name: "Transactions", exact: true }).click();

  await page.getByRole("button", { name: "Add transaction", exact: true }).click();
  let dialog = page.getByRole("dialog");
  await dialog.getByLabel("Date", { exact: true }).fill("2026-09-10");
  await dialog.getByLabel("Description", { exact: true }).fill("CHECKERS weekly groceries");
  await dialog.getByLabel("Amount (ZAR)", { exact: true }).fill("150");
  await expect(dialog.getByLabel("Category", { exact: true })).toHaveValue("Groceries");
  await expect(dialog.getByText(/Saved rule applied/)).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("positive-amount-entry.png"), fullPage: true });
  await dialog.getByLabel("Category", { exact: true }).selectOption("Food");
  await dialog.getByLabel("Description", { exact: true }).fill("CHECKERS weekly groceries updated");
  await expect(dialog.getByLabel("Category", { exact: true })).toHaveValue("Food");
  await dialog.getByLabel("Description", { exact: true }).fill("CHECKERS weekly groceries");
  await dialog.getByRole("button", { name: "Suggest category", exact: true }).click();
  await expect(dialog.getByText("Saved rule “Checkers” applied.", { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Save transaction", exact: true }).click();
  await expect(page.getByRole("cell", { name: "CHECKERS weekly groceries", exact: true })).toBeVisible();

  await page.getByRole("button", { name: "Add transaction", exact: true }).click();
  dialog = page.getByRole("dialog");
  await dialog.getByLabel("Date", { exact: true }).fill("2026-09-11");
  await dialog.getByLabel("Description", { exact: true }).fill("Salary payment");
  await dialog.getByLabel("Transaction type", { exact: true }).selectOption("income");
  await dialog.getByLabel("Amount (ZAR)", { exact: true }).fill("1000");
  await dialog.getByText("Always use this category for similar descriptions", { exact: true }).click();
  await dialog.getByLabel("Description contains", { exact: true }).fill("Salary");
  await dialog.getByRole("button", { name: "Save category rule", exact: true }).click();
  await expect(dialog.getByText("Category rule saved.", { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Save transaction", exact: true }).click();
  await expect(page.getByRole("cell", { name: "Salary payment", exact: true })).toBeVisible();
  const auth = await page.evaluate(() => localStorage.getItem("token"));
  const headers = { Authorization: "Bearer " + auth };
  const rows = await (await request.get("/api/transaction", { headers })).json();
  expect(rows.find((row: { description: string }) => row.description === "Salary payment").amount).toBe(1000);
  expect(rows.find((row: { description: string }) => row.description === "CHECKERS weekly groceries").amount).toBe(-150);

  await page.getByRole("checkbox", { name: "Select all listed transactions" }).check();
  await page.getByLabel("Category for selected transactions").selectOption("Shopping");
  await page.getByRole("button", { name: "Apply category", exact: true }).click();
  await expect(page.getByRole("cell", { name: "Shopping", exact: true })).toHaveCount(2);
  await page.getByRole("checkbox", { name: "Select transaction CHECKERS weekly groceries", exact: true }).check();
  await page.getByRole("button", { name: "Delete selected", exact: true }).click();
  await expect(page.getByRole("cell", { name: "CHECKERS weekly groceries", exact: true })).toHaveCount(0);
  let summary = await (await request.get("/api/budget/analytics?year=2026&month=9", { headers })).json();
  expect(summary.spent).toBe(0); expect(summary.income).toBe(1000);
  await page.getByRole("button", { name: "Undo deletion", exact: true }).click();
  await expect(page.getByRole("cell", { name: "CHECKERS weekly groceries", exact: true })).toBeVisible();
  const expenseRow = page.getByRole("row").filter({ has: page.getByRole("cell", { name: "CHECKERS weekly groceries", exact: true }) });
  await expenseRow.getByRole("button", { name: "Edit", exact: true }).click();
  await expect(page.getByRole("dialog").getByLabel("Transaction type", { exact: true })).toHaveValue("expense");
  await expect(page.getByRole("dialog").getByLabel("Amount (ZAR)", { exact: true })).toHaveValue("150");
  await page.keyboard.press("Escape");
  await expenseRow.getByRole("button", { name: "Delete", exact: true }).click();
  await expect(page.getByRole("cell", { name: "CHECKERS weekly groceries", exact: true })).toHaveCount(0);
  await page.reload();
  await page.getByLabel("View", { exact: true }).selectOption("deleted");
  await expect(page.getByRole("cell", { name: "CHECKERS weekly groceries", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("checkbox", { name: "Select all listed transactions" }).check();
  await page.getByRole("button", { name: "Restore selected", exact: true }).click();
  await expect(page.getByText("No deleted transactions match these filters.")).toBeVisible();
  await page.getByLabel("View", { exact: true }).selectOption("active");
  await expect(page.getByRole("cell", { name: "CHECKERS weekly groceries", exact: true })).toBeVisible();
  summary = await (await request.get("/api/budget/analytics?year=2026&month=9", { headers })).json();
  expect(summary.spent).toBe(150); expect(summary.netCashFlow).toBe(850);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("transaction-tools-mobile.png"), fullPage: true });
});
