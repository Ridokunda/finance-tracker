import { test, expect } from "@playwright/test";

test("recurring schedules, record/link payments, warning preferences and payment recovery", async ({ page, request }, testInfo) => {
  const credentials = { username: "planning-" + Date.now(), passwordHash: "Test-Rands-2026!" };
  expect((await request.post("/api/auth/register", { data: credentials })).ok()).toBeTruthy();
  await page.goto("/login");
  await page.getByLabel("Username", { exact: true }).fill(credentials.username);
  await page.getByLabel("Password", { exact: true }).fill(credentials.passwordHash);
  await page.getByRole("button", { name: "Login", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your monthly overview" })).toBeVisible();
  await page.getByLabel("Month", { exact: true }).fill("2026-09");
  const headers = { Authorization: "Bearer " + await page.evaluate(() => localStorage.getItem("token")) };
  const summary = async () => (await request.get("/api/budget/analytics?year=2026&month=9", { headers })).json();
  const transactions = async () => (await request.get("/api/transaction", { headers })).json();
  await page.getByRole("link", { name: "Budgets", exact: true }).click();
  await page.getByLabel("Overall monthly limit (ZAR)").fill("1000");
  await page.getByLabel("Allocate category", { exact: true }).selectOption("Entertainment");
  await page.getByRole("button", { name: "Add category limit", exact: true }).click();
  await page.getByLabel("Entertainment limit (ZAR)", { exact: true }).fill("1000");
  await page.getByRole("button", { name: "Save budget", exact: true }).click();
  await expect(page.getByText("Budget saved.", { exact: true })).toBeVisible();

  await page.getByRole("link", { name: "Recurring bills", exact: true }).click();
  await page.getByRole("button", { name: "Add recurring bill", exact: true }).click();
  let dialog = page.getByRole("dialog");
  await dialog.getByLabel("Bill name", { exact: true }).fill("Streaming");
  await dialog.getByLabel("Expected amount (ZAR)", { exact: true }).fill("800");
  await dialog.getByLabel("Category", { exact: true }).selectOption("Entertainment");
  await dialog.getByLabel("First due date", { exact: true }).fill("2026-09-10");
  await dialog.getByLabel("Statement description contains", { exact: true }).fill("Netflix");
  await dialog.getByRole("button", { name: "Save recurring bill", exact: true }).click();
  const streaming = page.getByRole("article", { name: "Streaming due 2026-09-10", exact: true });
  await expect(streaming.getByText("Overdue", { exact: true })).toBeVisible();
  expect(await transactions()).toEqual([]); expect((await summary()).spent).toBe(0);
  await page.getByRole("link", { name: "Dashboard", exact: true }).click();
  await expect(page.getByRole("region", { name: "Upcoming bills" }).getByText("Streaming", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Manage bills", exact: true }).click();

  let lookupOffline = true;
  await page.route("**/api/recurring-bills/*/payment-candidates?*", route => lookupOffline ? route.fulfill({ status: 503, body: "Temporary lookup outage" }) : route.continue());
  await streaming.getByRole("button", { name: "Record or link payment" }).click();
  dialog = page.getByRole("dialog");
  await dialog.getByLabel("Payment date", { exact: true }).fill("2026-09-10");
  await expect(dialog.getByRole("alert")).toContainText("Temporary lookup outage");
  await expect(dialog.getByRole("button", { name: /^(Link|Record) payment$/ })).toBeDisabled();
  expect(await transactions()).toEqual([]);
  lookupOffline = false;
  await dialog.getByRole("button", { name: "Retry lookup", exact: true }).click();
  await dialog.getByRole("button", { name: "Record payment", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(streaming.getByText("Paid", { exact: true })).toBeVisible();
  let rows = await transactions(); expect(rows).toHaveLength(1); expect(rows[0].amount).toBe(-800);
  const bills = await (await request.get("/api/recurring-bills", { headers })).json();
  expect((await request.post(`/api/recurring-bills/${bills[0].id}/payments`, { headers, data: { dueDate: "2026-09-10" } })).ok()).toBeTruthy();
  expect(await transactions()).toHaveLength(1);
  expect((await summary()).warnings.map((warning: { level: string }) => warning.level)).toEqual(["approaching", "approaching"]);
  await page.getByRole("link", { name: "Dashboard", exact: true }).click();
  await expect(page.getByRole("region", { name: "Budget warnings" }).getByText(/Approaching your limit/)).toHaveCount(2);
  await expect(page.getByText("No outstanding bills for this month.", { exact: false })).toBeVisible();

  await page.getByRole("link", { name: "Budgets", exact: true }).click();
  await page.getByLabel("Early warning at (%)", { exact: true }).fill("90");
  await page.getByRole("button", { name: "Save warning preferences", exact: true }).click();
  await expect(page.getByText("No budget warnings for this month.", { exact: true })).toBeVisible();
  await page.getByLabel("Enable budget warnings", { exact: true }).uncheck();
  await page.getByRole("button", { name: "Save warning preferences", exact: true }).click();
  await expect(page.getByText("Budget warnings are turned off.", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("Enable budget warnings", { exact: true })).not.toBeChecked();
  await expect(page.getByLabel("Early warning at (%)", { exact: true })).toHaveValue("90");
  await page.getByLabel("Enable budget warnings", { exact: true }).check();
  await page.getByLabel("Early warning at (%)", { exact: true }).fill("80");
  await page.getByRole("button", { name: "Save warning preferences", exact: true }).click();
  await expect(page.getByRole("region", { name: "Budget warnings" }).getByText(/Approaching your limit/)).toHaveCount(2);

  expect((await request.post("/api/transaction", { headers, data: { description: "Fibre debit", date: "2026-09-15", amount: 200, type: "expense", category: "Entertainment" } })).ok()).toBeTruthy();
  await page.reload();
  await expect(page.getByRole("region", { name: "Budget warnings" }).getByText(/Limit reached/)).toHaveCount(2);
  await page.getByRole("link", { name: "Recurring bills", exact: true }).click();
  await page.getByRole("button", { name: "Add recurring bill", exact: true }).click();
  dialog = page.getByRole("dialog");
  await dialog.getByLabel("Bill name", { exact: true }).fill("Internet");
  await dialog.getByLabel("Expected amount (ZAR)", { exact: true }).fill("200");
  await dialog.getByLabel("First due date", { exact: true }).fill("2026-09-15");
  await dialog.getByRole("button", { name: "Save recurring bill", exact: true }).click();
  const internet = page.getByRole("article", { name: "Internet due 2026-09-15", exact: true });
  await internet.getByRole("button", { name: "Record or link payment" }).click();
  dialog = page.getByRole("dialog");
  await dialog.getByLabel("Payment date", { exact: true }).fill("2026-09-15");
  await expect(dialog.getByLabel("Payment action", { exact: true })).toHaveValue("link");
  await expect(dialog.getByLabel("Existing expense", { exact: true })).toContainText("Fibre debit");
  await dialog.getByRole("button", { name: "Link payment", exact: true }).click();
  await expect(internet.getByText("Paid", { exact: true })).toBeVisible();
  expect(await transactions()).toHaveLength(2); expect((await summary()).spent).toBe(1000);

  // Recovering a deleted bill payment must restore its link and spending rather than add another expense.
  rows = await transactions(); const paid = rows.find((row: { description: string }) => row.description === "Streaming");
  expect((await request.post("/api/transaction/delete", { headers, data: { ids: [paid.id] } })).ok()).toBeTruthy();
  await page.reload();
  await expect(streaming.getByText("Payment deleted", { exact: true })).toBeVisible();
  await streaming.getByRole("link", { name: "Restore in Transactions" }).click();
  await expect(page.getByLabel("View", { exact: true })).toHaveValue("deleted");
  await page.getByRole("button", { name: "Restore", exact: true }).click();
  await page.getByRole("link", { name: "Recurring bills", exact: true }).click();
  await expect(streaming.getByText("Paid", { exact: true })).toBeVisible();
  expect(await transactions()).toHaveLength(2);
  const internetSchedule = page.getByRole("listitem").filter({ has: page.getByRole("heading", { name: "Internet", exact: true }) });
  await internetSchedule.getByRole("button", { name: "Pause reminders", exact: true }).click();
  await expect(internetSchedule.getByText(/Reminders paused/)).toBeVisible();
  await page.getByLabel("Month", { exact: true }).fill("2026-10");
  await expect(page.getByRole("article", { name: "Streaming due 2026-10-10", exact: true })).toBeVisible();
  await expect(page.getByRole("article", { name: "Internet due 2026-10-15", exact: true })).toHaveCount(0);
  await internetSchedule.getByRole("button", { name: "Resume reminders", exact: true }).click();
  await expect(page.getByRole("article", { name: "Internet due 2026-10-15", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("recurring-bills-mobile.png"), fullPage: true });
  await page.getByRole("button", { name: "Add recurring bill", exact: true }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  expect(await page.getByRole("dialog").evaluate(element => element.scrollWidth <= element.clientWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("bill-form-mobile.png"), fullPage: true });
  await page.keyboard.press("Escape");
  await internetSchedule.getByRole("button", { name: "Archive", exact: true }).click();
  await expect(page.getByRole("article", { name: "Internet due 2026-10-15", exact: true })).toHaveCount(0);
  await page.getByLabel("Month", { exact: true }).fill("2026-09");
  await expect(internet.getByText("Paid", { exact: true })).toBeVisible();

  expect((await request.post("/api/transaction", { headers, data: { description: "Extra expense", date: "2026-09-20", amount: 1, type: "expense", category: "Entertainment" } })).ok()).toBeTruthy();
  await page.getByRole("link", { name: "Budgets", exact: true }).click();
  await expect(page.getByRole("region", { name: "Budget warnings" }).getByText(/Over by/)).toHaveCount(2);
  await page.screenshot({ path: testInfo.outputPath("budget-warnings-mobile.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
});
